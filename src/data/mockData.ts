  const states = ['Gujarat', 'Tamil Nadu', 'Odisha', 'Assam', 'Punjab', 'Kerala', 'Jharkhand', 'Haryana', 'West Bengal', 'Andhra Pradesh', 'Uttarakhand'];
  
