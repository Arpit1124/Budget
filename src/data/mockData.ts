export function getDepartmentSector(code: string, name: string): string {
  const n = (name + ' ' + code).toLowerCase();
  if (
    n.includes('road') ||
    n.includes('rail') ||
    n.includes('transport') ||
    n.includes('highway') ||
    n.includes('urban') ||
    n.includes('housing') ||
    n.includes('port') ||
    n.includes('aviation') ||
    n.includes('shipping') ||
    n.includes('metro') ||
    n.includes('infra') ||
    code === 'MORTH' ||
    code === 'MOR' ||
    code === 'MOHUA' ||
    code === 'MOPSW' ||
    code === 'MOCA'
  ) {
    return 'Infrastructure';
  }
  if (
    n.includes('health') ||
    n.includes('family welfare') ||
    n.includes('drinking water') ||
    n.includes('sanitation') ||
    n.includes('jal shakti') ||
    n.includes('pharma') ||
    n.includes('ayush') ||
    code === 'MOHFW' ||
    code === 'MOJS' ||
    code === 'DDWS' ||
    code === 'DOP'
  ) {
    return 'Health & Sanitation';
  }
  if (
    n.includes('education') ||
    n.includes('literacy') ||
    n.includes('skill') ||
    n.includes('school') ||
    n.includes('higher education') ||
    n.includes('training') ||
    code === 'DSEL' ||
    code === 'DHE' ||
    code === 'MSDE'
  ) {
    return 'Education & Skills';
  }
  if (
    n.includes('agri') ||
    n.includes('rural') ||
    n.includes('farmer') ||
    n.includes('panchayat') ||
    n.includes('food') ||
    n.includes('fertilizer') ||
    n.includes('dairy') ||
    n.includes('fisheries') ||
    code === 'DAFW' ||
    code === 'MORD' ||
    code === 'MOPR' ||
    code === 'DFPD'
  ) {
    return 'Agriculture & Rural';
  }
  if (
    n.includes('power') ||
    n.includes('energy') ||
    n.includes('coal') ||
    n.includes('petroleum') ||
    n.includes('gas') ||
    n.includes('renewable') ||
    n.includes('atomic') ||
    n.includes('solar') ||
    code === 'MOP' ||
    code === 'MNRE'
  ) {
    return 'Energy & Power';
  }
  if (
    n.includes('tech') ||
    n.includes('electronics') ||
    n.includes('telecom') ||
    n.includes('science') ||
    n.includes('space') ||
    n.includes('earth science') ||
    n.includes('bio') ||
    code === 'MEITY' ||
    code === 'DOT' ||
    code === 'DST' ||
    code === 'MOES'
  ) {
    return 'Technology & Innovation';
  }
  if (
    n.includes('women') ||
    n.includes('child') ||
    n.includes('tribal') ||
    n.includes('social justice') ||
    n.includes('minority') ||
    n.includes('disability') ||
    n.includes('welfare') ||
    n.includes('labour') ||
    code === 'MWCD' ||
    code === 'MOTA' ||
    code === 'MOSJE' ||
    code === 'MOLE'
  ) {
    return 'Social Welfare';
  }
  if (
    n.includes('commerce') ||
    n.includes('industry') ||
    n.includes('textile') ||
    n.includes('steel') ||
    n.includes('mine') ||
    n.includes('msme') ||
    n.includes('corporate') ||
    n.includes('trade') ||
    n.includes('chemical') ||
    code === 'DCPC'
  ) {
    return 'Industry & Commerce';
  }
  return 'Governance & Administration';
}

